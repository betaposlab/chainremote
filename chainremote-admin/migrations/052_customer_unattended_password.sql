-- 052: 무인접속 비밀번호를 패널에서 정한다 (2026-09-05).
--
-- 무인접속 빌드(custom.txt 최상위 unattended=Y)는 approve-mode=both 라, **영구 비밀번호가
--   있으면** 수락 카드 없이 통과하고 없으면 카드로 폴백한다(server/connection.rs).
--   그런데 그 비밀번호를 정하는 길이 거래처 PC 앞에서 에이전트 창을 열고 손으로 넣는 것
--   하나뿐이었다 — 사람이 없어서 무인접속을 켜는 건데, 켜려면 사람이 가야 했다.
--
-- 2026-09-05 밤 달인식자재가 그 모순에 그대로 걸렸다. 사무실은 비었고 두 대는 켜져 있고
--   직원은 집에 있는데, 아무도 그 창을 열어 줄 수 없어 원격 자체가 불가능했다.
--
-- 그래서 대리점이 패널에서 정하고 하트비트가 실어 나른다. 에이전트는 서비스(세션0) 안에서
--   자기 config 에 직접 쓴다 — UI 를 거치는 IPC 경로는 무인 상태에서 어차피 실패한다.
--
-- ★왜 access_password 를 쓰지 않았나: 그 컬럼은 거래처 폼 입력이 그대로 들어가게 이미
--   배선돼 있다(lib/actions/customers.ts). 거기에 "원격 비밀번호" 의미를 얹으면, 지금은
--   화면에 입력칸이 없더라도 누가 되살리는 날 **아무 대리점이나 거래처 PC 에 원격 비번을
--   심을 수 있는** 길이 열린다. 의미가 다른 값은 칸을 나눠 둔다.
--
-- 문은 양쪽이 다 켜져야 열린다: ①이 값 ②그 대리점의 tenants.unattended_agent
-- ③설치본의 unattended=Y. 서버는 ②가 꺼진 대리점에는 키 자체를 안 내려보내고,
-- 에이전트는 ③이 없으면 뭐가 오든 무시한다. 한쪽 실수로는 열리지 않는다.
--
-- 비우면 다음 하트비트에 에이전트가 비밀번호를 지우고 수락 카드로 돌아간다. 그게 되돌리는 길.
--
-- 멱등: 컬럼 IF NOT EXISTS.

ALTER TABLE customers ADD COLUMN IF NOT EXISTS unattended_password text;
