-- 042: UPnP 로 연 문이 **바깥에서 실제로 열렸는지** 검증 (2026-08-12).
--
-- 왜 필요한가: 041 로 우리집 공유기에 포트를 열었더니 매핑은 멀쩡히 등록됐다 —
--   GetGenericPortMappingEntry 로 읽어도 TCP 21118 -> 192.168.68.100:21118, enabled=1,
--   임대까지 살아 있었다. 그런데 클라우드에서 그 주소로 접속하면 7ms 만에 붙고는 아무
--   응답이 없었고, 정작 PC 쪽 소켓 목록에는 그 연결이 **아예 없었다**. 공유기가 매핑을
--   받아 두기만 하고 랜 안쪽으로 넘기지 않은 것이다(같은 공유기의 다른 매핑 3개, 심지어
--   NAS 로 가는 것까지 전부 동일 증상. 매핑 없는 포트만 정상적으로 타임아웃).
--
-- 즉 **공유기의 "열었다"는 대답은 증거가 아니다.** 040 조사에서 54%가 "가능"으로 잡혔지만
--   그중 몇 곳이 이런 거짓 열림인지는 알 수 없다. 그래서 판정을 공유기 말이 아니라
--   바깥에서의 실측으로 바꾼다 — 클라우드(패널 서버)가 그 주소로 직접 접속해 보고,
--   에이전트의 인사(SignedId)까지 받아야 열린 문으로 인정한다.
--
-- ★"붙었다"로는 부족하고 첫 바이트까지 받아야 하는 이유가 위 사고 그 자체다. 붙기만
--   하는 문을 열린 것으로 세면 본사 앱이 매번 죽은 주소를 후보로 잡는다.
--
-- upnp_verified_at = 마지막으로 **바깥에서 열려 있음이 확인된** 시각(성공 시각).
-- upnp_probe_at    = 마지막 시도 시각(성공·실패 무관). 둘을 나눠 두면 "한 번도 확인 못 함"과
--                    "확인해 봤지만 닫혀 있음"이 구분된다.
--
-- 멱등: 컬럼 IF NOT EXISTS.

ALTER TABLE customers ADD COLUMN IF NOT EXISTS upnp_verified_at timestamptz;
ALTER TABLE customers ADD COLUMN IF NOT EXISTS upnp_probe_at timestamptz;
