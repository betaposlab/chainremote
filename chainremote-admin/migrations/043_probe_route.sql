-- 043: 연결 경로 점검(프로브) 결과 (2026-08-13).
--
-- 왜 필요한가: 직결 비율을 올리려면 **어느 거래처가 안 되는지**부터 알아야 하는데, 그걸 알
--   방법이 실제 원격뿐이었다. 30일에 원격 19건, 그중 경로가 기록된 건 2건이다 — 내부
--   기기(우리집·재성이 컴)는 지원기록을 안 남겨 세션이 아예 안 만들어지고, 15초 미만도
--   버려지기 때문이다. 이 속도로는 명단 하나 만드는 데 몇 달이 걸린다.
--
-- 그래서 HQ 가 거래처를 한 바퀴 돌며 **연결만 해 보고 끊는다**. 화면·입력은 건드리지 않고
--   거래처엔 수락 카드조차 안 뜬다(로그인 요청 전에 끊으므로).
--
-- ★비율이 아니라 명단이 목적이다. 거래처 26곳으로 비율을 재 봐야 ±19%p 밖에 못 좁힌다 —
--   표본 단위가 세션이 아니라 거래처이기 때문이다(같은 집을 100번 재도 NAT 는 하나다).
--   명단이 나오면 릴레이만 타는 집을 개별로 파거나, 다수면 릴레이를 받아들이고 화질 쪽을
--   손보면 된다. 그 판단에 필요한 건 숫자가 아니라 이름이다.
--
-- probe_direct = true(직결) / false(서버 경유) / NULL(측정 전이거나 연결 실패)
-- probe_at     = 마지막 측정 시각. 회선·공유기가 바뀌면 값이 낡으므로 시각을 같이 본다.
-- probe_ms     = 연결까지 걸린 시간(ms). 직결인데 느린 곳을 가려내는 데 쓴다.
--
-- 멱등: 컬럼 IF NOT EXISTS.

